fn finite(value: Option<String>, allowed: &[&str]) -> String {
    value
        .filter(|v| allowed.contains(&v.as_str()))
        .unwrap_or_else(|| "other".into())
}
pub(super) fn tag(fields: &Fields, key: &str, label: &str, allowed: &[&str]) -> String {
    format!("{label}:{}", finite(fields.get(key), allowed))
}
